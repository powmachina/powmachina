// mh-refvals — reference values for the bit-exact test of the GPU kernels (F3).
//
// It is not a second implementation of the algorithm — only a dump of what internal/mh
// computes, so the CUDA port of the primitives can be verified against it:
//
//	go run ./cmd/mh-refvals > machinahash-cuda/tests/refvals.txt
package main

import (
	"bufio"
	"encoding/hex"
	"fmt"
	"os"

	"github.com/zeebo/blake3"
)

// The inputs are chosen to cover the BLAKE3 block boundaries (64 B) and the longest input in MH-1.
var b3Lens = []int{0, 1, 31, 32, 63, 64, 65, 127, 128, 129, 255, 256, 284, 290, 512, 1023}

func main() {
	w := bufio.NewWriter(os.Stdout)
	defer w.Flush()
	fmt.Fprintln(w, "# reference values for machinahash-cuda (generated by `go run ./cmd/mh-refvals`)")

	for _, n := range b3Lens {
		in := make([]byte, n)
		for i := range in {
			in[i] = byte(i)*37 + 11
		}
		for _, outLen := range []int{32, 64, 256} {
			out := make([]byte, outLen)
			h := blake3.New()
			_, _ = h.Write(in)
			if _, err := h.Digest().Read(out); err != nil {
				fmt.Fprintln(os.Stderr, err)
				os.Exit(1)
			}
			fmt.Fprintf(w, "b3 %d %d %s %s\n",
				len(in), outLen, hex.EncodeToString(in), hex.EncodeToString(out))
		}
	}
}
